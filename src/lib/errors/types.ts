/**
 * Standard error domain classification across the application.
 */
export type ErrorDomain =
  | "ENGINE"
  | "ASSET"
  | "PARSER"
  | "SAVE"
  | "AUDIO"
  | "REACT"
  | "GAMEPLAY"
  | "SYSTEM"
  | "ARCHITECTURE";

/**
 * Severity level of the error condition.
 */
export type ErrorSeverity = "FATAL" | "ERROR" | "WARN" | "INFO";

